export function employerLogo({ id, company }) {
  const board = typeof id === 'string' ? id.split(':')[1]?.toLowerCase() : undefined;
  const name = typeof company === 'string' ? company.trim().toLowerCase() : undefined;
  const logo = Object.hasOwn(boardLogos, board) ? boardLogos[board]
    : Object.hasOwn(employerLogos, name) ? employerLogos[name] : null;
  return logo ? '/logos/' + logo + '.png' : null;
}
